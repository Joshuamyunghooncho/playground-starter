#!/usr/bin/env node
// Discovers every prototype under app/prototypes/<slug>/, validates it, and writes
// the generated registry files in lib/generated/. Runs automatically before
// dev, build, lint and typecheck. Fails loudly (exit 1) on an invalid prototype.
//
//   node scripts/generate-registry.mjs

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const prototypesDir = path.join(root, "app", "prototypes")
const thumbsDir = path.join(root, "public", "thumbnails")
const ogDir = path.join(root, "public", "og")
const outDir = path.join(root, "lib", "generated")

const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/
const REQUIRED_FILES = ["page.tsx", "metadata.json", "HOW_IT_WORKS.md"]

const errors = []

function fileVersion(p) {
  try {
    return Math.floor(fs.statSync(p).mtimeMs).toString(36)
  } catch {
    return null
  }
}

function validateMetadata(slug, m) {
  const where = `app/prototypes/${slug}/metadata.json`
  const fail = (msg) => errors.push(`${where}: ${msg}`)
  if (typeof m !== "object" || m === null || Array.isArray(m)) return fail("must be a JSON object")
  if (typeof m.title !== "string" || !m.title.trim()) fail(`"title" must be a non-empty string`)
  if (typeof m.description !== "string") fail(`"description" must be a string`)
  if (!Array.isArray(m.tags) || m.tags.some((t) => typeof t !== "string")) fail(`"tags" must be an array of strings`)
  if (typeof m.createdAt !== "string" || !DATE_RE.test(m.createdAt)) fail(`"createdAt" must be YYYY-MM-DD`)
  if (typeof m.updatedAt !== "string" || Number.isNaN(Date.parse(m.updatedAt))) fail(`"updatedAt" must be an ISO timestamp`)
  if (typeof m.hidden !== "boolean") fail(`"hidden" must be true or false`)
  if (typeof m.public !== "boolean") fail(`"public" must be true or false`)
}

const entries = []

if (fs.existsSync(prototypesDir)) {
  for (const dirent of fs.readdirSync(prototypesDir, { withFileTypes: true })) {
    if (!dirent.isDirectory()) continue
    const slug = dirent.name
    // Skip route groups, dynamic segments and private folders.
    if (slug.startsWith("[") || slug.startsWith("(") || slug.startsWith("_")) continue
    const dir = path.join(prototypesDir, slug)
    if (!SLUG_RE.test(slug)) {
      errors.push(`app/prototypes/${slug}: folder name must be kebab-case (a-z, 0-9, -)`)
      continue
    }
    const missing = REQUIRED_FILES.filter((f) => !fs.existsSync(path.join(dir, f)))
    if (missing.length) {
      errors.push(`app/prototypes/${slug}: missing ${missing.join(", ")}`)
      continue
    }
    let metadata
    try {
      metadata = JSON.parse(fs.readFileSync(path.join(dir, "metadata.json"), "utf8"))
    } catch (e) {
      errors.push(`app/prototypes/${slug}/metadata.json: invalid JSON (${e.message})`)
      continue
    }
    validateMetadata(slug, metadata)

    const light = fileVersion(path.join(thumbsDir, `${slug}-light.jpg`))
    const dark = fileVersion(path.join(thumbsDir, `${slug}-dark.jpg`))
    const ogImage = fileVersion(path.join(ogDir, `${slug}.png`))
    const ogMp4 = fileVersion(path.join(ogDir, `${slug}.mp4`))
    const ogWebm = fileVersion(path.join(ogDir, `${slug}.webm`))

    entries.push({
      slug,
      isPublic: metadata.public === true,
      assets: {
        thumbnailLight: light ? `/thumbnails/${slug}-light.jpg?v=${light}` : null,
        thumbnailDark: dark ? `/thumbnails/${slug}-dark.jpg?v=${dark}` : null,
        ogImage: ogImage ? `/og/${slug}.png?v=${ogImage}` : null,
        ogVideo: ogMp4
          ? { url: `/og/${slug}.mp4?v=${ogMp4}`, type: "video/mp4" }
          : ogWebm
            ? { url: `/og/${slug}.webm?v=${ogWebm}`, type: "video/webm" }
            : null,
      },
    })
  }
}

if (errors.length) {
  console.error("\n✖ Prototype registry: invalid prototypes\n")
  for (const e of errors) console.error("  - " + e)
  console.error("\nFix the issues above (see CLAUDE.md → Creating a prototype).\n")
  process.exit(1)
}

entries.sort((a, b) => a.slug.localeCompare(b.slug))
const ident = (slug) => "m_" + slug.replace(/-/g, "_")
const header = "// AUTO-GENERATED by scripts/generate-registry.mjs. Do not edit. Not committed.\n"

const registry =
  header +
  `import type { PrototypeEntry, PrototypeMetadata } from "@/lib/prototype-types"\n` +
  entries.map((e) => `import ${ident(e.slug)} from "@/app/prototypes/${e.slug}/metadata.json"\n`).join("") +
  `\nexport const registry: PrototypeEntry[] = [\n` +
  entries
    .map(
      (e) =>
        `  { slug: ${JSON.stringify(e.slug)}, metadata: ${ident(e.slug)} as PrototypeMetadata, assets: ${JSON.stringify(e.assets)} },\n`
    )
    .join("") +
  `]\n`

const publicOnes = entries.filter((e) => e.isPublic)

const publicSlugs =
  header +
  `// Imported by proxy.ts. Keep this file free of component imports.\n` +
  `export const publicSlugs: readonly string[] = ${JSON.stringify(publicOnes.map((e) => e.slug))}\n`

const publicComponents =
  header +
  `import type { ComponentType } from "react"\n` +
  publicOnes.map((e) => `import ${ident(e.slug)} from "@/app/prototypes/${e.slug}/page"\n`).join("") +
  `\nexport const publicComponents: Record<string, ComponentType> = {\n` +
  publicOnes.map((e) => `  ${JSON.stringify(e.slug)}: ${ident(e.slug)},\n`).join("") +
  `}\n`

fs.mkdirSync(outDir, { recursive: true })
const write = (name, content) => {
  const p = path.join(outDir, name)
  if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== content) fs.writeFileSync(p, content)
}
write("registry.ts", registry)
write("public-slugs.ts", publicSlugs)
write("public-components.tsx", publicComponents)

console.log(`✓ Prototype registry: ${entries.length} prototype(s), ${publicOnes.length} public`)
